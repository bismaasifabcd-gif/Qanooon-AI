import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { 
  ArrowLeft, 
  Trash2, 
  MessageSquare, 
  BookOpen, 
  Search, 
  ChevronDown, 
  ChevronUp, 
  Scale,
  X,
  AlertCircle,
  ExternalLink,
  Calendar,
  Clock,
  ChevronRight,
  Gavel,
  ShieldCheck,
  Download,
  FileText
} from 'lucide-react';
import { useLanguage } from '../contexts/LanguageContext';
import { useAuth } from '../contexts/AuthContext';
import { 
  collection, 
  query, 
  orderBy, 
  onSnapshot, 
  deleteDoc, 
  doc, 
  getDocs, 
  writeBatch 
} from 'firebase/firestore';
import { db } from '../firebase/config';
import { KanoonLogo, HistoryEmptyState } from '../components/SvgAssets';
import logo from '../assets/logo.png';
import FIRGenerator from '../components/FIRGenerator';
import ComplaintLetter from '../components/ComplaintLetter';

const History = () => {
  const navigate = useNavigate();
  const { t, language } = useLanguage();
  const { user } = useAuth();
  
  const [sessions, setSessions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState(null);
  const [showConfirm, setShowConfirm] = useState(null);
  const [isDeleting, setIsDeleting] = useState(false);
  const [activeGenerator, setActiveGenerator] = useState(null);

  const [activeTab, setActiveTab] = useState('sessions');
  const [documents, setDocuments] = useState([]);
  const [loadingDocs, setLoadingDocs] = useState(true);

  const toUrduNumerals = (str) => {
    if (language !== 'urdu') return str;
    const urduNumbers = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
    return str.toString().replace(/[0-9]/g, (w) => urduNumbers[+w]);
  };

  useEffect(() => {
    if (!user) return;
    const historyRef = collection(db, "users", user.uid, "history");
    const q = query(historyRef, orderBy("createdAt", "desc"));

    const unsubscribe = onSnapshot(q, (snapshot) => {
      setSessions(snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() })).slice(0, 50));
      setLoading(false);
    });
    return () => unsubscribe();
  }, [user]);

  useEffect(() => {
    if (!user) return;
    const docsRef = collection(db, "users", user.uid, "documents");
    const q = query(docsRef, orderBy("generatedAt", "desc"));

    const unsubscribe = onSnapshot(q, (snapshot) => {
      setDocuments(snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() })));
      setLoadingDocs(false);
    }, (error) => {
      console.error(error);
      setLoadingDocs(false);
    });
    return () => unsubscribe();
  }, [user]);

  const handleDelete = async (id) => {
    setIsDeleting(true);
    try {
      if (activeTab === 'sessions') {
        await deleteDoc(doc(db, "users", user.uid, "history", id));
      } else {
        await deleteDoc(doc(db, "users", user.uid, "documents", id));
      }
      setShowConfirm(null);
    } catch (error) {
      console.error(error);
    } finally {
      setIsDeleting(false);
    }
  };

  const handleDownloadPDF = (content, filename) => {
    import('jspdf').then(({ default: jsPDF }) => {
      const doc = new jsPDF();
      
      // Title
      doc.setFontSize(16);
      doc.setFont('helvetica', 'bold');
      doc.text('KANOON AI', 105, 20, { align: 'center' });
      
      doc.setFontSize(12);
      doc.text('Qanoon Sabke Liye Hai', 105, 28, { align: 'center' });
      
      // Divider line
      doc.line(10, 32, 200, 32);
      
      // Content
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      
      const lines = doc.splitTextToSize(content, 180);
      
      let y = 40;
      const pageHeight = doc.internal.pageSize.height;
      lines.forEach((line) => {
        if (y > pageHeight - 20) {
          doc.addPage();
          y = 20;
        }
        doc.text(line, 15, y);
        y += 6;
      });
      
      // Footer
      doc.setFontSize(8);
      doc.text('Generated by Kanoon AI — ' + new Date().toLocaleDateString(), 105, 285, { align: 'center' });
      
      doc.save(filename);
    });
  };

  const getBadgeStyle = (type) => {
    switch (type) {
      case 'chat': return 'bg-accent/10 text-accent border-accent/20';
      case 'law_viewed': return 'bg-blue-500/10 text-blue-500 border-blue-500/20';
      case 'lawyer_search': return 'bg-success/10 text-success border-success/20';
      default: return 'bg-primary/10 text-primary border-primary/20';
    }
  };

  const getTypeIcon = (type) => {
    switch (type) {
      case 'chat': return <MessageSquare className="w-4 h-4" />;
      case 'law_viewed': return <BookOpen className="w-4 h-4" />;
      case 'lawyer_search': return <Search className="w-4 h-4" />;
      default: return <Gavel className="w-4 h-4" />;
    }
  };

  return (
    <div className="min-h-screen bg-surface pb-24">
      {/* Premium Header */}
      <header className="bg-primary pt-12 pb-24 px-6 rounded-b-[3.5rem] relative overflow-hidden shadow-2xl">
        <div className="absolute top-0 right-0 w-96 h-96 bg-accent/5 rounded-full -translate-y-1/2 translate-x-1/2 blur-3xl" />
        <div className="absolute right-16 bottom-0 w-36 h-36 opacity-15 pointer-events-none hidden md:block">
          <HistoryEmptyState className="w-full h-full" />
        </div>
        
        <div className="max-w-4xl mx-auto relative z-10 flex items-center justify-between">
          <div className="flex items-center space-x-4 rtl:space-x-reverse">
            <button onClick={() => navigate('/dashboard')} className="w-12 h-12 bg-white/10 rounded-2xl flex items-center justify-center text-white hover:bg-accent hover:text-primary transition-all border border-white/10">
              <ArrowLeft className={`w-6 h-6 ${language === 'urdu' ? 'rotate-180' : ''}`} />
            </button>
            <img src={logo} alt="Kanoon AI Logo" className="app-logo w-9 h-9 object-cover" />
            <h1 className={`text-white text-3xl font-black ${language === 'urdu' ? 'font-urdu text-4xl' : ''}`}>
              {t.myHistory}
            </h1>
          </div>
          <button 
            onClick={() => setShowConfirm('all')}
            className="text-red-400 hover:text-red-300 font-black text-[10px] uppercase tracking-[0.2em] px-4 py-2 bg-white/5 rounded-xl border border-white/10 transition-all"
          >
            {t.clearAll}
          </button>
        </div>
      </header>

      <main className="max-w-4xl mx-auto px-4 sm:px-6 -mt-8 md:-mt-12 relative z-20 space-y-6 md:space-y-8">
        {/* Premium Tab Switcher */}
        <div className="flex bg-white/70 backdrop-blur-md p-1.5 rounded-[1.5rem] md:rounded-[2rem] border border-primary/5 shadow-xl">
          <button 
            onClick={() => setActiveTab('sessions')}
            className={`flex-1 py-3 md:py-4.5 rounded-[1.1rem] md:rounded-[1.7rem] font-black text-xs md:text-sm uppercase tracking-wider transition-all duration-300 ${
              activeTab === 'sessions' 
                ? 'bg-primary text-white shadow-lg' 
                : 'text-primary/40 hover:text-primary'
            }`}
          >
            {language === 'urdu' ? 'قانونی مشاورت' : 'Consultations'}
          </button>
          <button 
            onClick={() => setActiveTab('documents')}
            className={`flex-1 py-3 md:py-4.5 rounded-[1.1rem] md:rounded-[1.7rem] font-black text-xs md:text-sm uppercase tracking-wider transition-all duration-300 ${
              activeTab === 'documents' 
                ? 'bg-[#C9A84C] text-[#0F1E36] shadow-lg' 
                : 'text-primary/40 hover:text-[#C9A84C]'
            }`}
          >
            {language === 'urdu' ? 'قانونی دستاویزات' : 'Generated Documents'}
          </button>
        </div>

        {activeTab === 'sessions' ? (
          loading ? (
            Array(3).fill(0).map((_, i) => (
              <div key={i} className="bg-white h-24 rounded-[2rem] animate-pulse shadow-xl border border-primary/5" />
            ))
          ) : sessions.length === 0 ? (
            <div className="bg-white rounded-[2rem] md:rounded-[2.5rem] p-10 md:p-16 text-center space-y-6 shadow-xl border border-primary/5 animate-fade-up">
              <HistoryEmptyState className="w-36 h-36 md:w-48 md:h-48 mx-auto" />
              <div className="space-y-2">
                <h3 className="text-primary font-black text-xl md:text-2xl">{t.noHistoryYet}</h3>
                <p className="text-primary/40 font-medium max-w-xs mx-auto text-xs md:text-sm">{t.historyEmptySub}</p>
              </div>
              <button 
                onClick={() => navigate('/chatbot')}
                className="btn-justice mx-auto py-3.5 px-6 text-xs md:text-sm"
              >
                {t.getLegalHelp}
              </button>
            </div>
          ) : (
            <div className="space-y-4 animate-fade-up">
              {sessions.map((session) => (
                <div 
                  key={session.id}
                  className={`bg-white rounded-[2rem] shadow-xl shadow-primary/5 overflow-hidden transition-all duration-300 border border-primary/5 group ${
                    expandedId === session.id ? 'shadow-2xl shadow-primary/10 -translate-y-1' : 'hover:shadow-lg'
                  }`}
                >
                  <div 
                    className="p-4 sm:p-6 md:p-8 flex items-center justify-between cursor-pointer gap-2"
                    onClick={() => setExpandedId(expandedId === session.id ? null : session.id)}
                  >
                    <div className="flex items-center space-x-3 md:space-x-6 rtl:space-x-reverse min-w-0 flex-1">
                      <div className={`w-11 h-11 md:w-14 md:h-14 rounded-xl md:rounded-2xl border flex items-center justify-center flex-shrink-0 transition-all ${getBadgeStyle(session.type)}`}>
                        {getTypeIcon(session.type)}
                      </div>
                      <div className="space-y-0.5 min-w-0 flex-1">
                        <div className="flex items-center space-x-2 md:space-x-3 rtl:space-x-reverse">
                          <span className="text-[8px] md:text-[10px] font-black uppercase tracking-widest text-primary/30 truncate">
                            {t[session.type]}
                          </span>
                          <div className="w-1 h-1 bg-primary/10 rounded-full flex-shrink-0" />
                          <span className="text-primary/20 text-[8px] md:text-[10px] font-bold">
                            {toUrduNumerals(session.date || 'Today')}
                          </span>
                        </div>
                        <h3 className={`text-sm md:text-lg font-black text-primary group-hover:text-accent transition-colors truncate ${language === 'urdu' ? 'font-urdu text-base' : ''}`}>
                          {session.summary}
                        </h3>
                      </div>
                    </div>
                    <div className="flex items-center space-x-1.5 md:space-x-4 flex-shrink-0">
                      <div className={`p-1.5 md:p-2 rounded-lg transition-all ${expandedId === session.id ? 'bg-primary text-white rotate-180' : 'bg-surface text-primary group-hover:bg-accent'}`}>
                        <ChevronDown className="w-3.5 h-3.5" />
                      </div>
                      <button 
                        onClick={(e) => { e.stopPropagation(); setShowConfirm(session.id); }}
                        className="p-1.5 md:p-2 text-primary/10 hover:text-red-500 hover:bg-red-50 rounded-lg transition-all"
                      >
                        <Trash2 className="w-4 h-4 md:w-5 md:h-5" />
                      </button>
                    </div>
                  </div>

                  {/* Expanded Session View */}
                  {expandedId === session.id && (
                    <div className="px-4 pb-5 sm:px-8 sm:pb-8 animate-fade-up">
                      <div className="h-px bg-primary/5 mb-4 md:mb-6" />
                      {session.type === 'chat' && (
                        <div className="space-y-4 md:space-y-6">
                          <div className="flex items-center justify-between text-primary/30 text-[8px] md:text-[10px] font-black uppercase tracking-[0.2em]">
                            <span>Conversation Log</span>
                            <span>{toUrduNumerals(session.time || '14:20')}</span>
                          </div>
                          <div className="bg-surface rounded-2xl md:rounded-3xl p-4 md:p-6 space-y-4 border border-primary/5">
                            {session.messages?.slice(0, 2).map((msg, i) => (
                              <div key={i} className={`flex items-start space-x-2 md:space-x-3 rtl:space-x-reverse ${msg.role === 'user' ? 'opacity-50' : ''}`}>
                                <div className={`w-7 h-7 md:w-8 md:h-8 rounded-lg flex items-center justify-center flex-shrink-0 ${msg.role === 'user' ? 'bg-primary/10 text-primary' : 'bg-accent/10 text-accent'}`}>
                                  <Gavel className="w-3.5 h-3.5" />
                                </div>
                                <p className={`text-xs md:text-sm font-medium leading-relaxed ${language === 'urdu' ? 'font-urdu text-sm' : ''}`}>
                                  {msg.content.substring(0, 150)}...
                                </p>
                              </div>
                            ))}
                          </div>
                          {/* New Generate Document Action Buttons */}
                          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 mt-4">
                            <button 
                              onClick={() => setActiveGenerator({ type: 'fir', session })}
                              className="bg-[#0F1E36] hover:bg-[#C9A84C] hover:text-[#0F1E36] text-white font-black py-3 md:py-4.5 rounded-xl md:rounded-2xl flex items-center justify-center space-x-2 shadow-xl transition-all cursor-pointer text-xs md:text-sm"
                            >
                              <span>📄 {language === 'urdu' ? 'ایف آئی آر ڈرافٹ کریں' : 'Generate FIR Draft'}</span>
                            </button>
                            <button 
                              onClick={() => setActiveGenerator({ type: 'complaint', session })}
                              className="bg-white hover:bg-accent/10 text-primary border border-primary/10 font-black py-3 md:py-4.5 rounded-xl md:rounded-2xl flex items-center justify-center space-x-2 shadow-xl transition-all cursor-pointer text-xs md:text-sm"
                            >
                              <span>📝 {language === 'urdu' ? 'شکایتی خط بنائیں' : 'Generate Complaint Letter'}</span>
                            </button>
                          </div>

                          <button 
                            onClick={() => navigate('/chatbot', { state: { sessionId: session.id, resuming: true } })}
                            className="w-full border-2 border-primary/20 hover:bg-primary/5 text-primary font-black py-3 md:py-4 rounded-xl md:rounded-2xl flex items-center justify-center space-x-2 transition-all cursor-pointer text-xs md:text-sm mt-2"
                          >
                            <MessageSquare className="w-4 h-4" />
                            <span>Resume Legal Chat</span>
                          </button>
                        </div>
                      )}
                    </div>
                  )}
                </div>
              ))}
            </div>
          )
        ) : (
          loadingDocs ? (
            Array(3).fill(0).map((_, i) => (
              <div key={i} className="bg-white h-24 rounded-[2rem] animate-pulse shadow-xl border border-primary/5" />
            ))
          ) : documents.length === 0 ? (
            <div className="bg-white rounded-[2rem] md:rounded-[2.5rem] p-10 md:p-16 text-center space-y-6 shadow-xl border border-primary/5 animate-fade-up">
              <FileText className="w-16 h-16 md:w-20 md:h-20 mx-auto text-[#C9A84C]/45" />
              <div className="space-y-2">
                <h3 className="text-primary font-black text-xl md:text-2xl">
                  {language === 'urdu' ? 'کوئی دستاویز نہیں ملی' : 'No Legal Documents Yet'}
                </h3>
                <p className="text-primary/40 font-medium max-w-xs mx-auto text-xs md:text-sm">
                  {language === 'urdu' ? 'جب آپ AskLex کے ذریعے ایف آئی آر یا خط تیار کریں گے تو وہ یہاں محفوظ ہوں گے۔' : 'Documents generated via AskLex will be stored here for immediate download and print.'}
                </p>
              </div>
              <button 
                onClick={() => navigate('/chatbot')}
                className="btn-justice mx-auto py-3.5 px-6 text-xs md:text-sm"
              >
                {language === 'urdu' ? 'دستاویز تیار کریں' : 'Create a Document'}
              </button>
            </div>
          ) : (
            <div className="space-y-4 animate-fade-up">
              {documents.map((docItem) => (
                <div 
                  key={docItem.id}
                  className={`bg-white rounded-[2rem] shadow-xl shadow-primary/5 overflow-hidden transition-all duration-300 border border-primary/5 group ${
                    expandedId === docItem.id ? 'shadow-2xl shadow-primary/10 -translate-y-1' : 'hover:shadow-lg'
                  }`}
                >
                  <div 
                    className="p-4 sm:p-6 md:p-8 flex items-center justify-between cursor-pointer gap-2"
                    onClick={() => setExpandedId(expandedId === docItem.id ? null : docItem.id)}
                  >
                    <div className="flex items-center space-x-3 md:space-x-6 rtl:space-x-reverse min-w-0 flex-1">
                      <div className="w-11 h-11 md:w-14 md:h-14 rounded-xl md:rounded-2xl border flex items-center justify-center bg-[#C9A84C]/10 text-[#C9A84C] border-[#C9A84C]/20 flex-shrink-0">
                        <FileText className="w-5 h-5 md:w-6 md:h-6" />
                      </div>
                      <div className="space-y-0.5 min-w-0 flex-1 text-left rtl:text-right">
                        <div className="flex items-center space-x-2 md:space-x-3 rtl:space-x-reverse">
                          <span className="text-[8px] md:text-[10px] font-black uppercase tracking-widest text-[#C9A84C] truncate">
                            {docItem.type === 'fir_draft' 
                              ? (language === 'urdu' ? 'ایف آئی آر ڈرافٹ' : 'FIR Draft') 
                              : (language === 'urdu' ? 'شکایتی خط' : 'Complaint Letter')
                            }
                          </span>
                          <div className="w-1 h-1 bg-primary/10 rounded-full flex-shrink-0" />
                          <span className="text-primary/20 text-[8px] md:text-[10px] font-bold">
                            {docItem.generatedAt ? toUrduNumerals(new Date(docItem.generatedAt.seconds * 1000).toLocaleDateString()) : 'Today'}
                          </span>
                        </div>
                        <h3 className={`text-sm md:text-lg font-black text-primary group-hover:text-accent transition-colors truncate ${language === 'urdu' ? 'font-urdu text-base' : ''}`}>
                          {docItem.title || (docItem.type === 'fir_draft' ? 'FIR Draft' : 'Complaint Letter')}
                        </h3>
                      </div>
                    </div>
                    <div className="flex items-center space-x-1.5 md:space-x-4 flex-shrink-0">
                      <div className={`p-1.5 md:p-2 rounded-lg transition-all ${expandedId === docItem.id ? 'bg-primary text-white rotate-180' : 'bg-surface text-primary group-hover:bg-accent'}`}>
                        <ChevronDown className="w-3.5 h-3.5" />
                      </div>
                      <button 
                        onClick={(e) => { e.stopPropagation(); setShowConfirm(docItem.id); }}
                        className="p-1.5 md:p-2 text-primary/10 hover:text-red-500 hover:bg-red-50 rounded-lg transition-all"
                      >
                        <Trash2 className="w-4 h-4 md:w-5 md:h-5" />
                      </button>
                    </div>
                  </div>

                  {/* Expanded Document Content View */}
                  {expandedId === docItem.id && (
                    <div className="px-4 pb-5 sm:px-8 sm:pb-8 animate-fade-up text-left rtl:text-right space-y-4">
                      <div className="h-px bg-primary/5 mb-4" />
                      <div className="bg-surface rounded-2xl md:rounded-3xl p-4 md:p-6 border border-primary/5 text-primary text-xs md:text-sm font-semibold whitespace-pre-line leading-relaxed max-h-[250px] md:max-h-[300px] overflow-y-auto">
                        {docItem.content}
                      </div>
                      <button 
                        onClick={() => handleDownloadPDF(docItem.content, docItem.type === 'fir_draft' ? 'fir_draft.pdf' : 'complaint_letter.pdf')}
                        className="w-full bg-[#C9A84C] hover:bg-[#B3933C] text-[#0F1E36] font-black py-3 md:py-4 rounded-xl md:rounded-2xl flex items-center justify-center space-x-2 shadow-xl shadow-[#C9A84C]/10 transition-all text-xs md:text-sm"
                      >
                        <Download className="w-4 h-4 md:w-5 md:h-5 flex-shrink-0" />
                        <span>{language === 'urdu' ? 'پی ڈی ایف ڈاؤن لوڈ کریں' : 'Download Document PDF'}</span>
                      </button>
                    </div>
                  )}
                </div>
              ))}
            </div>
          )
        )}
      </main>

      {/* Confirmation Dialog Redesign */}
      {showConfirm && (
        <div className="fixed inset-0 z-[60] flex items-center justify-center p-6 bg-primary/40 backdrop-blur-md animate-fade-in">
          <div className="bg-white rounded-[2.5rem] p-10 max-w-sm w-full shadow-2xl border border-primary/5">
            <div className="w-20 h-20 bg-red-50 rounded-full flex items-center justify-center mb-8 mx-auto">
              <AlertCircle className="w-10 h-10 text-red-500" />
            </div>
            <div className="space-y-2 text-center">
              <h3 className="text-primary text-2xl font-black">
                {showConfirm === 'all' ? 'Purge All Records?' : 'Delete This Session?'}
              </h3>
              <p className="text-primary/40 text-sm font-medium">This action is permanent and cannot be reversed from the Justice Archive.</p>
            </div>
            <div className="flex space-x-4 rtl:space-x-reverse mt-10">
              <button 
                onClick={() => setShowConfirm(null)}
                className="flex-1 border-2 border-primary/5 hover:bg-primary/5 text-primary/60 font-bold py-4 rounded-2xl transition-all"
              >
                {t.cancel}
              </button>
              <button 
                onClick={() => showConfirm === 'all' ? navigate('/dashboard') : handleDelete(showConfirm)}
                disabled={isDeleting}
                className="flex-1 bg-red-500 hover:bg-red-600 text-white font-bold py-4 rounded-2xl transition-all shadow-xl shadow-red-500/20 disabled:opacity-50"
              >
                {isDeleting ? '...' : 'Confirm'}
              </button>
            </div>
          </div>
        </div>
      )}
      {activeGenerator?.type === 'fir' && (
        <FIRGenerator 
          session={activeGenerator.session} 
          onClose={() => setActiveGenerator(null)} 
        />
      )}
      {activeGenerator?.type === 'complaint' && (
        <ComplaintLetter 
          session={activeGenerator.session} 
          onClose={() => setActiveGenerator(null)} 
        />
      )}
    </div>
  );
};

export default History;

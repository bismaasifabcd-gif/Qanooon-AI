import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { 
  ArrowLeft, 
  Trash2, 
  MessageSquare, 
  BookOpen, 
  Search, 
  ChevronDown, 
  ChevronUp, 
  Scale,
  X,
  AlertCircle,
  ExternalLink,
  Calendar,
  Clock,
  ChevronRight,
  Gavel,
  ShieldCheck,
  Download,
  FileText
} from 'lucide-react';
import { useLanguage } from '../contexts/LanguageContext';
import { useAuth } from '../contexts/AuthContext';
import { 
  collection, 
  query, 
  orderBy, 
  onSnapshot, 
  deleteDoc, 
  doc, 
  getDocs, 
  writeBatch 
} from 'firebase/firestore';
import { db } from '../firebase/config';
import { KanoonLogo, HistoryEmptyState } from '../components/SvgAssets';
import logo from '../assets/logo.png';
import FIRGenerator from '../components/FIRGenerator';
import ComplaintLetter from '../components/ComplaintLetter';

const History = () => {
  const navigate = useNavigate();
  const { t, language } = useLanguage();
  const { user } = useAuth();
  
  const [sessions, setSessions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState(null);
  const [showConfirm, setShowConfirm] = useState(null);
  const [isDeleting, setIsDeleting] = useState(false);
  const [activeGenerator, setActiveGenerator] = useState(null);

  const [activeTab, setActiveTab] = useState('sessions');
  const [documents, setDocuments] = useState([]);
  const [loadingDocs, setLoadingDocs] = useState(true);

  const toUrduNumerals = (str) => {
    if (language !== 'urdu') return str;
    const urduNumbers = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
    return str.toString().replace(/[0-9]/g, (w) => urduNumbers[+w]);
  };

  useEffect(() => {
    if (!user) return;
    const historyRef = collection(db, "users", user.uid, "history");
    const q = query(historyRef, orderBy("createdAt", "desc"));

    const unsubscribe = onSnapshot(q, (snapshot) => {
      setSessions(snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() })).slice(0, 50));
      setLoading(false);
    });
    return () => unsubscribe();
  }, [user]);

  useEffect(() => {
    if (!user) return;
    const docsRef = collection(db, "users", user.uid, "documents");
    const q = query(docsRef, orderBy("generatedAt", "desc"));

    const unsubscribe = onSnapshot(q, (snapshot) => {
      setDocuments(snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() })));
      setLoadingDocs(false);
    }, (error) => {
      console.error(error);
      setLoadingDocs(false);
    });
    return () => unsubscribe();
  }, [user]);

  const handleDelete = async (id) => {
    setIsDeleting(true);
    try {
      if (activeTab === 'sessions') {
        await deleteDoc(doc(db, "users", user.uid, "history", id));
      } else {
        await deleteDoc(doc(db, "users", user.uid, "documents", id));
      }
      setShowConfirm(null);
    } catch (error) {
      console.error(error);
    } finally {
      setIsDeleting(false);
    }
  };

  const handleDownloadPDF = (content, filename) => {
    import('jspdf').then(({ default: jsPDF }) => {
      const doc = new jsPDF();
      
      // Title
      doc.setFontSize(16);
      doc.setFont('helvetica', 'bold');
      doc.text('QANOON AI', 105, 20, { align: 'center' });
      
      doc.setFontSize(12);
      doc.text('Qanoon Sabke Liye Hai', 105, 28, { align: 'center' });
      
      // Divider line
      doc.line(10, 32, 200, 32);
      
      // Content
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      
      const lines = doc.splitTextToSize(content, 180);
      
      let y = 40;
      const pageHeight = doc.internal.pageSize.height;
      lines.forEach((line) => {
        if (y > pageHeight - 20) {
          doc.addPage();
          y = 20;
        }
        doc.text(line, 15, y);
        y += 6;
      });
      
      // Footer
      doc.setFontSize(8);
      doc.text('Generated by Qanoon AI — ' + new Date().toLocaleDateString(), 105, 285, { align: 'center' });
      
      doc.save(filename);
    });
  };

  const getBadgeStyle = (type) => {
    switch (type) {
      case 'chat': return 'bg-accent/10 text-accent border-accent/20';
      case 'law_viewed': return 'bg-blue-500/10 text-blue-500 border-blue-500/20';
      case 'lawyer_search': return 'bg-success/10 text-success border-success/20';
      default: return 'bg-primary/10 text-primary border-primary/20';
    }
  };

  const getTypeIcon = (type) => {
    switch (type) {
      case 'chat': return <MessageSquare className="w-4 h-4" />;
      case 'law_viewed': return <BookOpen className="w-4 h-4" />;
      case 'lawyer_search': return <Search className="w-4 h-4" />;
      default: return <Gavel className="w-4 h-4" />;
    }
  };

  return (
    <div className="min-h-screen bg-surface pb-24">
      {/* Header — rectangular, matches dashboard */}
      <header className="bg-primary px-5 md:px-8 pt-6 pb-6 border-b-2 border-accent/30">
        <div className="max-w-4xl mx-auto flex items-center justify-between gap-3">
          <div className="flex items-center gap-3 min-w-0">
            <button onClick={() => navigate('/dashboard')} className="w-10 h-10 bg-white/10 rounded-lg flex items-center justify-center text-white hover:bg-accent hover:text-primary transition-all flex-shrink-0">
              <ArrowLeft className={`w-5 h-5 ${language === 'urdu' ? 'rotate-180' : ''}`} />
            </button>
            <img src={logo} alt="Qanoon AI Logo" className="app-logo w-9 h-9 object-cover border border-white/10" />
            <h1 className={`text-white text-xl md:text-2xl font-black ${language === 'urdu' ? 'font-urdu text-2xl' : ''}`}>
              {t.myHistory}
            </h1>
          </div>
          <button 
            onClick={() => setShowConfirm('all')}
            className="text-red-300 hover:text-red-200 font-bold text-[10px] uppercase tracking-wider px-3 py-1.5 bg-white/5 rounded-lg transition-all flex-shrink-0"
          >
            {t.clearAll}
          </button>
        </div>
      </header>

      <main className="max-w-4xl mx-auto px-5 md:px-8 pt-6 relative z-20 space-y-4">
        {/* Tab Switcher */}
        <div className="flex bg-white p-1 rounded-xl border border-primary/8 shadow-sm">
          <button 
            onClick={() => setActiveTab('sessions')}
            className={`flex-1 py-2.5 rounded-lg font-black text-xs uppercase tracking-wider transition-all ${
              activeTab === 'sessions' ? 'bg-primary text-white' : 'text-primary/40 hover:text-primary'
            }`}
          >
            {language === 'urdu' ? 'مشاورت' : 'Chats'}
          </button>
          <button 
            onClick={() => setActiveTab('documents')}
            className={`flex-1 py-2.5 rounded-lg font-black text-xs uppercase tracking-wider transition-all ${
              activeTab === 'documents' ? 'bg-accent text-primary' : 'text-primary/40 hover:text-accent'
            }`}
          >
            {language === 'urdu' ? 'دستاویزات' : 'Documents'}
          </button>
        </div>

        {activeTab === 'sessions' ? (
          loading ? (
            Array(3).fill(0).map((_, i) => (
              <div key={i} className="bg-white h-20 rounded-xl animate-pulse shadow-sm border border-primary/8" />
            ))
          ) : sessions.length === 0 ? (
            <div className="bg-white rounded-xl p-8 md:p-12 text-center space-y-5 shadow-sm border border-primary/8 animate-fade-up">
              <HistoryEmptyState className="w-28 h-28 md:w-36 md:h-36 mx-auto" />
              <div className="space-y-1.5">
                <h3 className="text-primary font-black text-lg md:text-xl">{t.noHistoryYet}</h3>
                <p className="text-primary/40 font-medium max-w-xs mx-auto text-xs md:text-sm">{t.historyEmptySub}</p>
              </div>
              <button 
                onClick={() => navigate('/chatbot')}
                className="btn-justice mx-auto py-3 px-6 text-xs md:text-sm rounded-lg"
              >
                {t.getLegalHelp}
              </button>
            </div>
          ) : (
            <div className="space-y-3 animate-fade-up">
              {sessions.map((session) => (
                <div 
                  key={session.id}
                  className="bg-white rounded-xl shadow-sm overflow-hidden transition-all duration-200 border border-primary/8 group hover:border-accent/30"
                >
                  <div 
                    className="p-4 flex items-center justify-between cursor-pointer gap-2"
                    onClick={() => setExpandedId(expandedId === session.id ? null : session.id)}
                  >
                    <div className="flex items-center gap-3 min-w-0 flex-1">
                      <div className={`w-10 h-10 rounded-lg border flex items-center justify-center flex-shrink-0 ${getBadgeStyle(session.type)}`}>
                        {getTypeIcon(session.type)}
                      </div>
                      <div className="space-y-0.5 min-w-0 flex-1">
                        <div className="flex items-center gap-2">
                          <span className="text-[9px] font-black uppercase tracking-widest text-primary/30 truncate">
                            {t[session.type]}
                          </span>
                          <div className="w-1 h-1 bg-primary/10 rounded-full flex-shrink-0" />
                          <span className="text-primary/20 text-[9px] font-bold">
                            {toUrduNumerals(session.date || 'Today')}
                          </span>
                        </div>
                        <h3 className={`text-sm font-black text-primary group-hover:text-accent transition-colors truncate ${language === 'urdu' ? 'font-urdu text-base' : ''}`}>
                          {session.summary}
                        </h3>
                      </div>
                    </div>
                    <div className="flex items-center gap-1.5 flex-shrink-0">
                      <div className={`p-1.5 rounded-md transition-all ${expandedId === session.id ? 'bg-primary text-white rotate-180' : 'bg-surface text-primary group-hover:bg-accent'}`}>
                        <ChevronDown className="w-3.5 h-3.5" />
                      </div>
                      <button 
                        onClick={(e) => { e.stopPropagation(); setShowConfirm(session.id); }}
                        className="p-1.5 text-primary/15 hover:text-red-500 hover:bg-red-50 rounded-md transition-all"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </div>

                  {/* Expanded Session View */}
                  {expandedId === session.id && (
                    <div className="px-4 pb-4 animate-fade-up">
                      <div className="h-px bg-primary/5 mb-3" />
                      {session.type === 'chat' && (
                        <div className="space-y-3">
                          <div className="bg-surface rounded-lg p-4 space-y-3 border border-primary/5">
                            {session.messages?.slice(0, 2).map((msg, i) => (
                              <div key={i} className={`flex items-start gap-2 ${msg.role === 'user' ? 'opacity-50' : ''}`}>
                                <div className={`w-7 h-7 rounded-md flex items-center justify-center flex-shrink-0 ${msg.role === 'user' ? 'bg-primary/10 text-primary' : 'bg-accent/10 text-accent'}`}>
                                  <Gavel className="w-3.5 h-3.5" />
                                </div>
                                <p className={`text-xs md:text-sm font-medium leading-relaxed ${language === 'urdu' ? 'font-urdu text-sm' : ''}`}>
                                  {msg.content.substring(0, 150)}...
                                </p>
                              </div>
                            ))}
                          </div>
                          {/* Generate Document buttons */}
                          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                            <button 
                              onClick={() => setActiveGenerator({ type: 'fir', session })}
                              className="bg-primary hover:bg-accent hover:text-primary text-white font-bold py-2.5 rounded-lg flex items-center justify-center gap-1.5 transition-all text-xs"
                            >
                              <span>📄 {language === 'urdu' ? 'ایف آئی آر ڈرافٹ' : 'FIR Draft'}</span>
                            </button>
                            <button 
                              onClick={() => setActiveGenerator({ type: 'complaint', session })}
                              className="bg-white hover:bg-accent/10 text-primary border border-primary/10 font-bold py-2.5 rounded-lg flex items-center justify-center gap-1.5 transition-all text-xs"
                            >
                              <span>📝 {language === 'urdu' ? 'شکایتی خط' : 'Complaint Letter'}</span>
                            </button>
                          </div>

                          <button 
                            onClick={() => navigate('/chatbot', { state: { sessionId: session.id, resuming: true } })}
                            className="w-full border border-primary/15 hover:bg-primary/5 text-primary font-bold py-2.5 rounded-lg flex items-center justify-center gap-2 transition-all text-xs"
                          >
                            <MessageSquare className="w-4 h-4" />
                            <span>{language === 'urdu' ? 'گفتگو جاری رکھیں' : 'Resume Chat'}</span>
                          </button>
                        </div>
                      )}
                    </div>
                  )}
                </div>
              ))}
            </div>
          )
        ) : (
          loadingDocs ? (
            Array(3).fill(0).map((_, i) => (
              <div key={i} className="bg-white h-20 rounded-xl animate-pulse shadow-sm border border-primary/8" />
            ))
          ) : documents.length === 0 ? (
            <div className="bg-white rounded-xl p-8 md:p-12 text-center space-y-5 shadow-sm border border-primary/8 animate-fade-up">
              <FileText className="w-14 h-14 md:w-16 md:h-16 mx-auto text-[#C9A84C]/45" />
              <div className="space-y-1.5">
                <h3 className="text-primary font-black text-lg md:text-xl">
                  {language === 'urdu' ? 'کوئی دستاویز نہیں' : 'No Documents Yet'}
                </h3>
                <p className="text-primary/40 font-medium max-w-xs mx-auto text-xs md:text-sm">
                  {language === 'urdu' ? 'جب آپ ایف آئی آر یا خط تیار کریں گے تو وہ یہاں محفوظ ہوں گے۔' : 'FIRs and letters you generate will be saved here for download.'}
                </p>
              </div>
              <button 
                onClick={() => navigate('/chatbot')}
                className="btn-justice mx-auto py-3 px-6 text-xs md:text-sm rounded-lg"
              >
                {language === 'urdu' ? 'دستاویز تیار کریں' : 'Create a Document'}
              </button>
            </div>
          ) : (
            <div className="space-y-3 animate-fade-up">
              {documents.map((docItem) => (
                <div 
                  key={docItem.id}
                  className="bg-white rounded-xl shadow-sm overflow-hidden transition-all duration-200 border border-primary/8 group hover:border-accent/30"
                >
                  <div 
                    className="p-4 flex items-center justify-between cursor-pointer gap-2"
                    onClick={() => setExpandedId(expandedId === docItem.id ? null : docItem.id)}
                  >
                    <div className="flex items-center gap-3 min-w-0 flex-1">
                      <div className="w-10 h-10 rounded-lg border flex items-center justify-center bg-[#C9A84C]/10 text-[#C9A84C] border-[#C9A84C]/20 flex-shrink-0">
                        <FileText className="w-5 h-5" />
                      </div>
                      <div className="space-y-0.5 min-w-0 flex-1 text-left rtl:text-right">
                        <div className="flex items-center gap-2">
                          <span className="text-[9px] font-black uppercase tracking-widest text-[#C9A84C] truncate">
                            {docItem.type === 'fir_draft' 
                              ? (language === 'urdu' ? 'ایف آئی آر ڈرافٹ' : 'FIR Draft') 
                              : (language === 'urdu' ? 'شکایتی خط' : 'Complaint Letter')
                            }
                          </span>
                          <div className="w-1 h-1 bg-primary/10 rounded-full flex-shrink-0" />
                          <span className="text-primary/20 text-[9px] font-bold">
                            {docItem.generatedAt ? toUrduNumerals(new Date(docItem.generatedAt.seconds * 1000).toLocaleDateString()) : 'Today'}
                          </span>
                        </div>
                        <h3 className={`text-sm font-black text-primary group-hover:text-accent transition-colors truncate ${language === 'urdu' ? 'font-urdu text-base' : ''}`}>
                          {docItem.title || (docItem.type === 'fir_draft' ? 'FIR Draft' : 'Complaint Letter')}
                        </h3>
                      </div>
                    </div>
                    <div className="flex items-center gap-1.5 flex-shrink-0">
                      <div className={`p-1.5 rounded-md transition-all ${expandedId === docItem.id ? 'bg-primary text-white rotate-180' : 'bg-surface text-primary group-hover:bg-accent'}`}>
                        <ChevronDown className="w-3.5 h-3.5" />
                      </div>
                      <button 
                        onClick={(e) => { e.stopPropagation(); setShowConfirm(docItem.id); }}
                        className="p-1.5 text-primary/15 hover:text-red-500 hover:bg-red-50 rounded-md transition-all"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </div>

                  {/* Expanded Document Content View */}
                  {expandedId === docItem.id && (
                    <div className="px-4 pb-4 animate-fade-up text-left rtl:text-right space-y-3">
                      <div className="h-px bg-primary/5 mb-3" />
                      <div className="bg-surface rounded-lg p-4 border border-primary/5 text-primary text-xs md:text-sm font-medium whitespace-pre-line leading-relaxed max-h-[250px] overflow-y-auto">
                        {docItem.content}
                      </div>
                      <button 
                        onClick={() => handleDownloadPDF(docItem.content, docItem.type === 'fir_draft' ? 'fir_draft.pdf' : 'complaint_letter.pdf')}
                        className="w-full bg-accent hover:bg-[#B3933C] text-primary font-black py-3 rounded-lg flex items-center justify-center gap-2 transition-all text-xs md:text-sm"
                      >
                        <Download className="w-4 h-4 flex-shrink-0" />
                        <span>{language === 'urdu' ? 'پی ڈی ایف ڈاؤن لوڈ' : 'Download PDF'}</span>
                      </button>
                    </div>
                  )}
                </div>
              ))}
            </div>
          )
        )}
      </main>

      {/* Confirmation Dialog */}
      {showConfirm && (
        <div className="fixed inset-0 z-[60] flex items-center justify-center p-6 bg-primary/40 backdrop-blur-md animate-fade-in">
          <div className="bg-white rounded-2xl p-6 max-w-sm w-full shadow-2xl border border-primary/5">
            <div className="w-14 h-14 bg-red-50 rounded-xl flex items-center justify-center mb-5 mx-auto">
              <AlertCircle className="w-7 h-7 text-red-500" />
            </div>
            <div className="space-y-1.5 text-center">
              <h3 className="text-primary text-lg font-black">
                {showConfirm === 'all'
                  ? (language === 'urdu' ? 'سب کچھ حذف کریں؟' : 'Clear all history?')
                  : (language === 'urdu' ? 'یہ حذف کریں؟' : 'Delete this item?')}
              </h3>
              <p className="text-primary/50 text-sm font-medium">
                {language === 'urdu' ? 'یہ عمل مستقل ہے اور واپس نہیں ہو سکتا۔' : 'This is permanent and cannot be undone.'}
              </p>
            </div>
            <div className="flex gap-3 mt-6">
              <button 
                onClick={() => setShowConfirm(null)}
                className="flex-1 border border-primary/10 hover:bg-primary/5 text-primary/60 font-bold py-3 rounded-xl transition-all"
              >
                {t.cancel}
              </button>
              <button 
                onClick={() => showConfirm === 'all' ? navigate('/dashboard') : handleDelete(showConfirm)}
                disabled={isDeleting}
                className="flex-1 bg-red-500 hover:bg-red-600 text-white font-bold py-3 rounded-xl transition-all disabled:opacity-50"
              >
                {isDeleting ? '...' : (language === 'urdu' ? 'تصدیق' : 'Confirm')}
              </button>
            </div>
          </div>
        </div>
      )}
      {activeGenerator?.type === 'fir' && (
        <FIRGenerator 
          session={activeGenerator.session} 
          onClose={() => setActiveGenerator(null)} 
        />
      )}
      {activeGenerator?.type === 'complaint' && (
        <ComplaintLetter 
          session={activeGenerator.session} 
          onClose={() => setActiveGenerator(null)} 
        />
      )}
    </div>
  );
};

export default History;
